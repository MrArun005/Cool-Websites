// REPORT.md, generated from state only (src/analysis.js). No hand-typed numbers, no clock:
// running it twice on the same state gives the same bytes. Bad news is reported in the same voice as good news.
//   npm run report                      -> <chartsDir>/REPORT.md
//   npm run report -- --update-readme   -> also refreshes the generated block in README.md
//   npm run report -- --dry-run         -> from .dry-run/
import fs from 'node:fs';
import path from 'node:path';
import { loadConfig, rootPath } from './config.js';
import { analyze } from './analysis.js';
import { variantBudget } from './variants.js';
import { writeText, isoDay, MS_PER_SECOND } from './util.js';

const PCT_DIGITS = 1;

const pct = (v) => (v === null || v === undefined || Number.isNaN(v) ? 'n/a' : `${(v * 100).toFixed(PCT_DIGITS)}%`);
const pts = (v) => (v === null || v === undefined || Number.isNaN(v) ? 'n/a' : `${v >= 0 ? '+' : ''}${(v * 100).toFixed(PCT_DIGITS)} pts`);
const ci = (lo, hi) => `[${pct(lo)}, ${pct(hi)}]`;
const ptsCI = (d) => `${pts(d.estimate)} (95% CI ${pts(d.low)} to ${pts(d.high)})`;
const day = isoDay;
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(esc).join(' | ')} |`)].join('\n');
const leverText = (l) => Object.entries(l).filter(([, on]) => on).map(([k]) => k).join(' + ') || 'none';
const fmtNum = (v, digits = 1) => (v === null || v === undefined ? 'n/a' : Number(v).toFixed(digits));

function meaning(d) {
  if (!d) return 'not enough data yet';
  return d.significant ? (d.estimate > 0 ? 'statistically meaningful improvement' : 'statistically meaningful drop') : 'not statistically meaningful (the 95% CI includes zero)';
}

export function buildReport(cfg, a) {
  const L = [];
  const mock = cfg.llm.provider === 'mock';
  const runs = a.generatedFrom.runs;
  L.push('# Self-improving coder: report');
  L.push('');
  L.push(`_Generated by \`npm run report\` from \`${cfg.paths.stateDir}\`. Every number below comes from the raw logs; do not edit by hand._`);
  L.push(`_Data: ${runs} evaluated runs across ${Object.keys(a.variants).length} variants, last run ${day(a.generatedFrom.lastTs)}._`);
  L.push('');
  if (mock) {
    L.push('> **These numbers come from the synthetic mock provider, not from a language model.** They exercise the pipeline,');
    L.push('> statistics and gate; they say nothing about how well any model learns.');
    L.push('');
  }
  if (!runs) {
    L.push('No evaluated runs yet. Run the workflow (or `npm run reproduce`) first.');
    L.push('');
  }

  // Setup
  const mv = cfg.variants[0];
  const vb = variantBudget(cfg, mv.name);
  L.push('## Setup');
  L.push('');
  L.push(`- **Model:** \`${cfg.llm.model}\` via \`${cfg.llm.provider}\`${mock ? ' (mock)' : ''}; train temperature ${cfg.llm.temperature}, eval temperature ${cfg.eval.temperature}.`);
  L.push(`- **MultiPL-E track:** HumanEval + MBPP in JavaScript (dataset revision \`${cfg.dataset.revision.slice(0, cfg.output.shortShaChars)}\`), ${cfg.split.holdoutSize} holdout problems, split seed ${cfg.split.seed}.`);
  L.push(`- **Mutation track:** killed mutants of \`${cfg.curriculum.name}\` @ \`${cfg.curriculum.repo.commit.slice(0, cfg.output.shortShaChars)}\` (${cfg.curriculum.repo.license}), judged by its own test suite; holdout mutants come from seed ${cfg.curriculum.holdoutSeed}, never trained on.`);
  L.push(`- **Evaluation:** every holdout evaluation runs ${cfg.eval.repeats} times with different sampling seeds; scores are the mean per problem, CIs are ${Math.round(cfg.stats.confidence * 100)}% percentile bootstrap over problems (${cfg.stats.bootstrapResamples} resamples).`);
  L.push(`- **Gate (${cfg.gate.method}):** accept if the candidate is at least ${pts(cfg.gate.minImprovement)} better${cfg.gate.method === 'ci' ? ' and the paired CI of the difference excludes zero' : ''}; reject if worse by more than ${pts(cfg.gate.tolerance)}${cfg.gate.method === 'ci' ? ' or the CI is entirely below zero' : ''}; otherwise keep the change pending (max ${cfg.gate.maxPendingRuns} runs). The first ${cfg.gate.baselineRuns} runs of every variant only measure the starting point.`);
  L.push(`- **Budget:** ${cfg.budget.totalRequestsPerRun} model requests per day split over ${cfg.variants.length} variants (${vb.requestsPerRun} each at equal shares, ${Math.round(cfg.budget.holdoutFraction * 100)}% reserved for evaluation).`);
  L.push('');

  // Variants
  L.push('## Variants');
  L.push('');
  L.push(table(['variant', 'track', 'levers', 'evaluated runs', 'accepted lessons', 'accepted skills', 'prompt'],
    Object.values(a.variants).map((v) => [`${v.label}${v.control ? ' (control)' : ''}`, v.track, leverText(v.levers), v.runs.length, v.liveLessons, v.liveSkills, v.promptVersion ?? 'n/a'])));
  L.push('');

  // Headline
  L.push('## Results: holdout pass rate');
  L.push('');
  for (const [track, t] of Object.entries(a.tracks)) {
    L.push(`### ${track}`);
    L.push('');
    const comp = new Map(t.comparisons.map((c) => [c.variant, c]));
    L.push(table(['variant', 'latest pass rate', '95% CI', 'n x repeats', 'change since its start', 'minus the control\'s change', 'vs control (same day)'],
      t.variants.map((name) => {
        const v = a.variants[name];
        const c = comp.get(name);
        return [`${v.label}${v.control ? ' (control)' : ''}`, pct(v.latest?.passRate), v.latest ? ci(v.latest.ciLow, v.latest.ciHigh) : 'n/a', v.latest ? `${v.latest.n} x ${v.latest.repeats}` : 'n/a',
          v.vsBaseline ? ptsCI(v.vsBaseline) : 'n/a', v.control ? 'n/a' : v.vsBaselineAdjusted ? ptsCI(v.vsBaselineAdjusted) : 'n/a', v.control ? 'n/a' : c ? ptsCI(c) : 'n/a'];
      })));
    L.push('');
    const ctrl = t.control ? a.variants[t.control] : null;
    if (ctrl?.vsBaseline) {
      L.push(`The control (no memory, no learning) moved ${ptsCI(ctrl.vsBaseline)} between its starting runs and its latest run: ${ctrl.vsBaseline.significant ? '**this drift is itself statistically meaningful**, so a variant\'s change since its start is not evidence on its own' : 'that is the size of day-to-day noise'}. That is why the comparisons below subtract the control.`);
      L.push('');
    }
    for (const name of t.variants) {
      const v = a.variants[name];
      if (v.control) continue;
      const c = comp.get(name);
      L.push(`- **${v.label}:** vs the control on the same day: ${meaning(c)}${c ? ` (${ptsCI(c)})` : ''}; change since its start minus the control's change: ${meaning(v.vsBaselineAdjusted)}${v.vsBaselineAdjusted ? ` (${ptsCI(v.vsBaselineAdjusted)})` : ''}.`);
    }
    L.push('');
  }

  // Difficulty
  L.push('## Difficulty check');
  L.push('');
  for (const [track, t] of Object.entries(a.tracks)) {
    const d = t.difficulty;
    if (d.status === 'no-data') L.push(`- **${track}:** no baseline runs yet.`);
    else if (d.status === 'ok') L.push(`- **${track}:** starting pass rate ${pct(d.start)}, inside the useful range (${pct(d.floorRate)}-${pct(d.ceilingRate)}).`);
    else L.push(`- **${track}: ${d.status === 'floor' ? 'floor effect' : 'ceiling effect'}.** Starting pass rate ${pct(d.start)} is ${d.status === 'floor' ? 'below' : 'above'} ${pct(d.limit)}, so this track can show little either way. To change the difficulty: ${d.hint ?? 'see config'}.`);
  }
  L.push('');

  // Cost
  L.push('## Cost');
  L.push('');
  L.push('_"Solved" = distinct train problems passed at least once. Requests include reflection calls._');
  L.push('');
  L.push(table(['variant', 'train requests', 'eval requests', 'tokens in / out', 'train problems solved', 'solved per 100 requests', 'requests per solved', 'tokens per solved', 'seconds per request'],
    Object.values(a.variants).map((v) => [v.label, v.cost.trainRequests, v.cost.evalRequests, `${v.cost.tokensIn} / ${v.cost.tokensOut}`, `${v.cost.trainSolved} of ${v.cost.trainProblemsTried}`,
      fmtNum(v.cost.solvedPer100Requests), fmtNum(v.cost.requestsPerSolved), fmtNum(v.cost.tokensPerSolved, 0), v.cost.msPerRequest === null ? 'n/a' : fmtNum(v.cost.msPerRequest / MS_PER_SECOND, 2)])));
  L.push('');

  // Taxonomy
  L.push('## Failure types');
  L.push('');
  L.push('Share of champion holdout attempts in each class, first evaluated run vs latest. A class counts as **reduced** by self-improvement when a learning variant\'s share drops by at least ' + pts(cfg.analysis.taxonomyMinDrop) + ' and clearly more than the control\'s.');
  L.push('');
  for (const [track, t] of Object.entries(a.tracks)) {
    L.push(`### ${track}`);
    L.push('');
    L.push(table(['class', 'meaning', 'control change', 'learning variants (change)', 'verdict'],
      t.taxonomyChange.map((x) => [x.class, cfg.taxonomy.description[x.class], pts(x.controlDelta), x.learners.map((l) => `${a.variants[l.variant].label} ${pts(l.delta)}`).join('; ') || 'n/a', x.verdict])));
    L.push('');
    const reduced = t.taxonomyChange.filter((x) => x.verdict === 'reduced').map((x) => x.class);
    const not = t.taxonomyChange.filter((x) => x.verdict === 'not-reduced').map((x) => x.class);
    L.push(`**Which failure types does self-improvement fix here?** ${reduced.length ? reduced.join(', ') : 'none so far'}. **Which does it not fix?** ${not.length ? not.join(', ') : 'n/a'}.`);
    L.push('');
  }

  // Curriculum
  L.push('## Curriculum levels (mutation track)');
  L.push('');
  const cur = Object.values(a.variants).filter((v) => v.curriculum);
  if (!cur.length) L.push('No curriculum state yet.');
  for (const v of cur) {
    const ups = v.curriculum.history.map((h) => `level ${h.from} -> ${h.to} after a rolling pass rate of ${pct(h.rollingPassRate)} over ${h.window} tasks (run ${h.runIndex})`);
    L.push(`- **${v.label}:** level ${v.curriculum.level} reached${ups.length ? `; ${ups.join('; ')}` : '; no level changes yet'}.`);
  }
  L.push('');

  // Gate log
  L.push('## Gate decisions');
  L.push('');
  L.push(table(['variant', 'baseline', 'accept', 'keep', 'reject', 'no-change', 'no-eval'], Object.values(a.variants).map((v) => {
    const n = (d) => v.gateLog.filter((g) => g.decision === d).length;
    return [v.label, n('baseline'), n('accept'), n('keep'), n('reject'), n('no-change'), n('no-eval')];
  })));
  L.push('');

  // Plateau
  L.push('## Where it plateaued');
  L.push('');
  for (const v of Object.values(a.variants).filter((x) => !x.control)) {
    const p = v.plateau;
    if (p.status === 'too-early') L.push(`- **${v.label}:** too early to tell (${p.runsSoFar} learning runs, need ${p.runsNeeded}).`);
    else L.push(`- **${v.label}:** ${p.status === 'plateaued' ? `**plateaued**: no statistically meaningful gain over the last ${p.K} runs` : `still improving over the last ${p.K} runs`} (${ptsCI(p.diff)} since ${day(p.since)}, ${p.accepted} accepted change(s) in that window).`);
  }
  L.push('');

  // Blocked
  L.push('## Changes the gate blocked');
  L.push('');
  const rejects = Object.values(a.variants).flatMap((v) => v.gateLog.filter((g) => g.decision === 'reject').map((g) => ({ v, g })));
  if (!rejects.length) L.push('The gate has not rejected anything yet.');
  else {
    L.push(table(['date', 'variant', 'champion', 'rejected candidate', 'difference', 'what it would have added'], rejects.map(({ v, g }) => [day(g.ts), v.label, pct(g.champion?.passRate), pct(g.candidate?.passRate),
      g.diff ? ptsCI(g.diff) : 'n/a', `${g.added.lessons} lessons, ${g.added.skills} skills${g.added.promptVersion ? `, prompt ${g.added.promptVersion}` : ''}`])));
    const total = rejects.reduce((s, { g }) => s + (g.diff?.estimate ?? 0), 0);
    const sig = rejects.filter(({ g }) => g.diff && g.diff.high < 0).length;
    L.push('');
    L.push(`Without the gate, each of these candidates would have replaced its champion. Summing the measured differences, that would have ${total < 0 ? 'lowered' : 'raised'} holdout pass rate by ${Math.abs(total * 100).toFixed(PCT_DIGITS)} pts in total. Only ${sig} of ${rejects.length} drops had a CI entirely below zero; the others were rejected because the drop exceeded the tolerance, so some of them may be noise.`);
  }
  L.push('');

  // Lessons
  L.push('## Lessons');
  L.push('');
  for (const v of Object.values(a.variants).filter((x) => x.lessons.length)) {
    const never = v.lessons.filter((l) => l.trainRetrievals > 0 && l.trainPasses === 0);
    const best = [...v.lessons].sort((x, y) => y.trainPasses - x.trainPasses || x.id.localeCompare(y.id)).slice(0, cfg.analysis.reportTopLessons);
    L.push(`### ${v.label}`);
    L.push('');
    L.push(`${v.lessons.length} lessons created; ${v.lessons.filter((l) => l.status === 'accepted').length} accepted, ${v.lessons.filter((l) => l.status === 'pending').length} pending, ${v.lessons.filter((l) => l.status === 'dropped').length} dropped. ${never.length} were retrieved but never on a passing attempt.`);
    L.push('');
    L.push(table(['lesson', 'status', 'born from', 'retrieved (train)', 'passing when retrieved'], best.map((l) => [`${l.id}: ${l.text}`, l.status, `${l.born.problemId} (${l.born.failureClass})`, l.trainRetrievals, l.trainPasses])));
    L.push('');
    if (v.conflicts.length) {
      L.push('**Lessons that conflicted** (retrieved together on failed attempts, with a lower pass rate together than either alone):');
      L.push('');
      for (const c of v.conflicts.slice(0, cfg.analysis.reportTopConflicts)) L.push(`- ${c.a} + ${c.b}: failed together ${c.failedTogether} of ${c.together} times (pass rate together ${pct(c.passRateTogether)}, alone ${pct(c.passRateA)} / ${pct(c.passRateB)})`);
    } else L.push('No conflicting lesson pairs detected.');
    L.push('');
  }

  L.push("## What I'd do with real compute");
  L.push('');
  L.push('> TODO (author): this section is deliberately left for the human author.');
  L.push('');
  L.push('## Reproduce');
  L.push('');
  L.push('```bash');
  L.push('npm ci');
  L.push('npm run reproduce -- --variant=lessons-skills --seed=1   # offline, mock provider');
  L.push('npm run report');
  L.push('```');
  L.push('');
  return L.join('\n');
}

const README_START = '<!-- report:summary:start -->';
const README_END = '<!-- report:summary:end -->';

/** Short generated block for README: headline per learning variant + the failure-type answer. */
export function readmeBlock(cfg, a) {
  const L = [README_START, `_Generated by \`npm run report\` from the committed state (${a.generatedFrom.runs} evaluated runs, last ${day(a.generatedFrom.lastTs)}). Details: [REPORT.md](REPORT.md)._`, ''];
  for (const [track, t] of Object.entries(a.tracks)) {
    for (const c of t.comparisons) L.push(`- **${track} / ${a.variants[c.variant].label}** vs control: ${ptsCI(c)}: ${meaning(c)}.`);
    const reduced = t.taxonomyChange.filter((x) => x.verdict === 'reduced').map((x) => x.class);
    const not = t.taxonomyChange.filter((x) => x.verdict === 'not-reduced').map((x) => x.class);
    L.push(`- **${track} failure types** reduced by self-improvement: ${reduced.join(', ') || 'none so far'}; not reduced: ${not.join(', ') || 'n/a'}.`);
  }
  if (!a.generatedFrom.runs) L.push('- No runs yet.');
  L.push(README_END);
  return L.join('\n');
}

export function updateReadme(text, block) {
  const i = text.indexOf(README_START);
  const j = text.indexOf(README_END);
  if (i < 0 || j < 0) throw new Error('README is missing the report:summary markers');
  return text.slice(0, i) + block + text.slice(j + README_END.length);
}

export function writeReport(cfg, { updateReadmeFile = false } = {}) {
  const a = analyze(cfg);
  const md = buildReport(cfg, a);
  writeText(rootPath(cfg, cfg.paths.chartsDir, cfg.paths.reportFile), md);
  if (updateReadmeFile) {
    const file = rootPath(cfg, cfg.paths.readme);
    writeText(file, updateReadme(fs.readFileSync(file, 'utf8'), readmeBlock(cfg, a)));
  }
  return md;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const cfg = loadConfig({ dryRun: process.argv.includes('--dry-run') });
  writeReport(cfg, { updateReadmeFile: process.argv.includes('--update-readme') });
  console.log(path.relative(process.cwd(), rootPath(cfg, cfg.paths.chartsDir, cfg.paths.reportFile)));
}
