// The curriculum's third-party repo: fetched at a pinned commit into the (git-ignored) cache, its dev
// packages installed without install scripts, and its own test suite run in the PLAN.md sandbox.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { rootPath, deepMerge } from '../config.js';
import { runNode } from '../judge/run-tests.js';
import { log } from '../util.js';

/** Effective curriculum config: `curriculum.fixture` is merged over it when useFixtureRepo is on. */
export function curriculumCfg(cfg) {
  const c = cfg.curriculum;
  return c.useFixtureRepo ? deepMerge(c, c.fixture) : c;
}

/** Ensure the repo + its dev packages are present. Returns { repoDir, depsDir|null }. */
export function ensureRepo(cfg) {
  const c = curriculumCfg(cfg);
  if (c.useFixtureRepo) return { repoDir: rootPath(cfg, c.fixtureRepo), depsDir: null };
  const cache = rootPath(cfg, c.cacheDir);
  const repoDir = path.join(cache, `${c.name}@${c.repo.commit}`);
  if (!fs.existsSync(path.join(repoDir, '.sic-complete'))) {
    fs.rmSync(repoDir, { recursive: true, force: true });
    fs.mkdirSync(repoDir, { recursive: true });
    const git = (...args) => execFileSync('git', args, { cwd: repoDir, stdio: ['ignore', 'pipe', 'pipe'] });
    log(`curriculum: fetching ${c.repo.url} @ ${c.repo.commit}`);
    git('init', '-q');
    git('fetch', '-q', '--depth', '1', c.repo.url, c.repo.commit);
    git('checkout', '-q', 'FETCH_HEAD');
    const head = git('rev-parse', 'HEAD').toString().trim();
    if (head !== c.repo.commit) throw new Error(`curriculum: expected commit ${c.repo.commit}, got ${head}`);
    fs.writeFileSync(path.join(repoDir, '.sic-complete'), head + '\n');
  }
  let depsDir = null;
  if (c.devPackages.length) {
    depsDir = path.join(cache, `${c.name}-deps-${c.devPackages.join('_').replace(/[^\w.@-]/g, '_')}`);
    if (!fs.existsSync(path.join(depsDir, '.sic-complete'))) {
      fs.rmSync(depsDir, { recursive: true, force: true });
      fs.mkdirSync(depsDir, { recursive: true });
      fs.writeFileSync(path.join(depsDir, 'package.json'), '{"private":true}\n');
      log(`curriculum: installing ${c.devPackages.join(', ')} (no install scripts)`);
      execFileSync('npm', ['install', '--ignore-scripts', '--no-audit', '--no-fund', '--save-exact', ...c.devPackages], { cwd: depsDir, stdio: ['ignore', 'pipe', 'pipe'] });
      fs.writeFileSync(path.join(depsDir, '.sic-complete'), 'ok\n');
    }
  }
  return { repoDir, depsDir };
}

/** Test files to run, relative to the repo root, sorted. */
export function testFiles(repoDir, c) {
  const dir = path.join(repoDir, c.testDir);
  return fs.readdirSync(dir).filter((f) => f.endsWith(c.testSuffix) && !c.excludeTests.includes(f)).sort().map((f) => `${c.testDir}/${f}`);
}

/** Runner that requires every test file in one process; optionally hides passing TAP lines so failures fit the output cap. */
export function runnerSource(files, hideOkPattern) {
  return [
    "'use strict'",
    '// generated by self-improving-coder: runs the repository\'s own test files in one process',
    "const path = require('path')",
    hideOkPattern ? `const okLine = new RegExp(${JSON.stringify(hideOkPattern)})
const write = process.stdout.write.bind(process.stdout)
process.stdout.write = (chunk, ...rest) => write(String(chunk).split('\\n').filter((l) => !okLine.test(l)).join('\\n'), ...rest)` : '',
    `for (const f of ${JSON.stringify(files)}) require(path.join(__dirname, f))`,
    '',
  ].join('\n');
}

/**
 * Copy the repo's code + tests into a fresh temp dir, overwrite `files` ({ relPath: source }),
 * run the suite sandboxed, delete the dir. Returns the judge result { type, output, durationMs }.
 */
export async function runSuite(cfg, env, files = {}) {
  const c = curriculumCfg(cfg);
  const dir = fs.mkdtempSync(path.join(cfg.judge.tmpRoot || os.tmpdir(), 'sic-mut-'));
  try {
    for (const p of c.copyPaths) fs.cpSync(path.join(env.repoDir, p), path.join(dir, p), { recursive: true });
    for (const [rel, src] of Object.entries(files)) fs.writeFileSync(path.join(dir, rel), src);
    if (env.depsDir) fs.symlinkSync(path.join(env.depsDir, 'node_modules'), path.join(dir, 'node_modules'), 'dir');
    const runner = path.join(dir, c.runnerFile);
    fs.writeFileSync(runner, runnerSource(testFiles(env.repoDir, c), c.hideOkLines ? c.okLinePattern : null));
    return await runNode({ dir, entry: runner, judgeCfg: cfg.judge, extraReadDirs: env.depsDir ? [env.depsDir] : [], timeoutMs: c.testTimeoutMs });
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}
