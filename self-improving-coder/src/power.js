// Power analysis by simulation, using the exact CI code the gate uses.
// Question: with n holdout problems x r repeats, how big must a real improvement be before the gate's
// paired CI excludes zero most of the time (power >= target)?
// Problem difficulties are drawn from a seeded uniform range; a candidate's per-problem pass probability is
// the champion's plus `effect` (clamped). Writes a Markdown table (default docs/power.md).
//   npm run power
import path from 'node:path';
import { loadConfig, rootPath } from './config.js';
import { pairedGroupCI } from './stats.js';
import { rng, hash32, writeText } from './util.js';

export function simulatePower({ n, repeats, effect, sims, resamples, confidence, method, seed, pLow, pHigh }) {
  let detected = 0;
  for (let s = 0; s < sims; s++) {
    const r = rng(hash32(`${seed}|${n}|${repeats}|${effect}|${s}`));
    const champ = [];
    const cand = [];
    for (let i = 0; i < n; i++) {
      const p = pLow + r() * (pHigh - pLow);
      const q = Math.min(1, Math.max(0, p + effect));
      champ.push(Array.from({ length: repeats }, () => (r() < p ? 1 : 0)));
      cand.push(Array.from({ length: repeats }, () => (r() < q ? 1 : 0)));
    }
    const ci = pairedGroupCI(champ, cand, { resamples, confidence, seed: hash32(`ci|${s}`) }, method);
    if (ci.low > 0) detected++;
  }
  return detected / sims;
}

/** Smallest effect on the grid with power >= target, per (n, repeats). */
export function powerTable(cfg) {
  const pc = cfg.power;
  const rows = [];
  for (const n of pc.holdoutSizes) {
    for (const repeats of pc.repeats) {
      const powers = pc.effects.map((effect) => simulatePower({ n, repeats, effect, sims: pc.sims, resamples: pc.resamples, confidence: cfg.stats.confidence, method: cfg.stats.method, seed: pc.seed, pLow: pc.passProbabilityRange[0], pHigh: pc.passProbabilityRange[1] }));
      const idx = powers.findIndex((p) => p >= pc.targetPower);
      rows.push({ n, repeats, powers, minDetectable: idx >= 0 ? pc.effects[idx] : null });
    }
  }
  return rows;
}

export function powerMarkdown(cfg, rows) {
  const pc = cfg.power;
  const pts = (e) => `${(e * 100).toFixed(0)} pts`;
  const L = ['# Statistical power of the holdout gate', '',
    `_Generated by \`npm run power\` from \`config/default.json\` (simulation, ${pc.sims} simulated comparisons per cell, ${cfg.stats.method} bootstrap with ${pc.resamples} resamples, ${Math.round(cfg.stats.confidence * 100)}% CI). Do not edit by hand._`, '',
    `Each cell is the share of simulated runs in which the paired CI of (candidate - champion) excludes zero, i.e. the gate could accept, when the candidate truly is better by the column's effect. Problem pass probabilities are drawn uniformly from ${pc.passProbabilityRange[0]}-${pc.passProbabilityRange[1]}.`, '',
    `| holdout n | repeats | ${pc.effects.map(pts).join(' | ')} | smallest effect with power >= ${Math.round(pc.targetPower * 100)}% |`,
    `|---|---|${pc.effects.map(() => '---').join('|')}|---|`];
  for (const r of rows) L.push(`| ${r.n} | ${r.repeats} | ${r.powers.map((p) => `${Math.round(p * 100)}%`).join(' | ')} | ${r.minDetectable === null ? `> ${pts(pc.effects.at(-1))}` : pts(r.minDetectable)} |`);
  const cur = rows.find((r) => r.n === cfg.split.holdoutSize && r.repeats === cfg.eval.repeats);
  L.push('');
  if (cur) L.push(`**Current setting (n = ${cur.n}, ${cur.repeats} repeats):** the smallest true improvement the gate detects at least ${Math.round(pc.targetPower * 100)}% of the time is ${cur.minDetectable === null ? `more than ${pts(pc.effects.at(-1))}` : `about ${pts(cur.minDetectable)}`}. Smaller real gains will mostly be kept pending or missed; that is the price of not accepting noise.`);
  L.push('');
  return L.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const cfg = loadConfig();
  const md = powerMarkdown(cfg, powerTable(cfg));
  const file = rootPath(cfg, cfg.power.outFile);
  writeText(file, md);
  console.log(md);
  console.log(path.relative(process.cwd(), file));
}
