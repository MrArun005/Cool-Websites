"""Contact odometry for the hybrid duck: where the robot is, from its feet + IMU.

A Python port of Pollen Robotics' Microduck runtime `odometry` crate (microduck/odometry/src/lib.rs + anchors.rs,
Apache-2.0, itself derived from Rhoban's humanoid `model_service`); line for line it matches their own Python
replica (`PyOdometry` in microduck_rl/scripts/infer_policy.py). The idea: at any moment one point of one sole is the
robot's contact with the ground. Anchor that point to the world (Z = 0, X/Y wherever it was when it became the
anchor), orient the trunk by the IMU, and the trunk's world position follows by forward kinematics of the measured
leg joints. When another sole point drops 1 cm below the ground plane (a step landing) and stays the lowest for 2
ticks (40 ms at 50 Hz), the anchor moves there, at that point's current world X/Y, so the estimate never jumps.
Heading is the IMU's (no magnetometer): here a simulated IMU fusion (SimIMU: gyro quaternion + accelerometer tilt,
with sensor noise and bias), not soccer.py's gyro-about-gravity integration, which drifts ~0.25 deg/s while walking.

The hybrid walks on Microduck's legs and soles, so their anchor points apply unchanged: running their
`odom_anchor_points.py --scene scene_hybrid_allcollisions_noantenna.xml` on our model gives the same ALPHA16 / ALPHA4
/ V15 sets to 1e-8 m (sites `left_foot` / `right_foot`, sole meshes `left_foot_collision` / `right_foot_collision`).
Forward kinematics: MuJoCo's own (mj_kinematics on a private MjData of the hybrid model, trunk at the origin), fed
only the 14 measured servo angles - what the robot's encoders give - instead of their `kinematics` crate.

    from odometry import Odometry, SimOdometry
    odo = Odometry()                               # ALPHA16, the production set
    odo.update(joints14, quat_wxyz)                # harness.JOINT_NAMES order (no mouth); IMU trunk orientation
    odo.position, odo.yaw                          # trunk in the odometry's world frame (m, rad)
    odo.set_pose((x, y), yaw)                      # re-anchor to a known pose (a landmark sighting)

    so = SimOdometry(sim, pos0=(x, y), yaw0=psi)  # glue for MicroduckSim: noisy encoders + simulated IMU fusion
    rt.on_substep = so.substep                     # (or call so.substep(sim) from your own 200 Hz callback)
    ... rt.tick(); so.update()                     # after every 50 Hz tick
    so.xy, so.yaw                                  # field-frame estimate
    so.set_pose((x, y), yaw)                       # a landmark fix (goal sighting)

Evaluation (odometry_eval.py): see the README section "Contact odometry".
"""
