def quat_to_mat(q):
    w, x, y, z = np.asarray(q, float) / np.linalg.norm(q)
    return np.array([[1 - 2 * (y * y + z * z), 2 * (x * y - w * z), 2 * (x * z + w * y)],
                     [2 * (x * y + w * z), 1 - 2 * (x * x + z * z), 2 * (y * z - w * x)],
                     [2 * (x * z - w * y), 2 * (y * z + w * x), 1 - 2 * (x * x + y * y)]])


def yaw_of(R):
    return math.atan2(R[1, 0], R[0, 0])


def rot_z(a):
    c, s = math.cos(a), math.sin(a)
    return np.array([[c, -s, 0.0], [s, c, 0.0], [0.0, 0.0, 1.0]])


def imu_rotation(gravity_body, yaw):
    """Trunk-in-world rotation from what an IMU gives: gravity in the trunk frame (accelerometer / fusion; upright =
    (0, 0, -1)) and a heading. The tilt is the shortest rotation taking the trunk's down to the world's down."""
    g = np.asarray(gravity_body, float)
    g = g / np.linalg.norm(g)
    a, b = -g, np.array([0.0, 0.0, 1.0])          # trunk-frame "up" -> world up
    v, c = np.cross(a, b), float(a @ b)
    if c < -0.999999:
        R0 = np.diag([1.0, -1.0, -1.0])
    else:
        vx = np.array([[0, -v[2], v[1]], [v[2], 0, -v[0]], [-v[1], v[0], 0]])
        R0 = np.eye(3) + vx + vx @ vx / (1 + c)
    return rot_z(yaw - yaw_of(R0)) @ R0


class LegFK:
    """Foot-site poses in the trunk frame from the 14 servo angles (encoders), via MuJoCo kinematics."""

    def __init__(self, scene=SCENE, model=None):
        import mujoco
        self.mj = mujoco
        self.m = model if model is not None else mujoco.MjModel.from_xml_path(str(scene))
        self.d = mujoco.MjData(self.m)
        self.qadr = [int(self.m.jnt_qposadr[self.m.joint(n).id]) for n in JOINT_NAMES]
        self.sites = [self.m.site(f"{s}_foot").id for s in ("left", "right")]
        self.trunk = self.m.body("trunk_base").id
        self.d.qpos[:] = self.m.qpos0
        a = int(self.m.jnt_qposadr[self.m.body_jntadr[self.trunk]])      # the trunk's free joint
        self.d.qpos[a:a + 7] = [0, 0, 0, 1, 0, 0, 0]

    def feet(self, joints):
        self.d.qpos[self.qadr] = joints
        self.mj.mj_kinematics(self.m, self.d)
        Rt, pt = self.d.xmat[self.trunk].reshape(3, 3), self.d.xpos[self.trunk]
        return [(Rt.T @ (self.d.site_xpos[s] - pt), Rt.T @ self.d.site_xmat[s].reshape(3, 3)) for s in self.sites]


class Odometry:
    """microduck/odometry `Odometry` (lib.rs), for the hybrid. Call update() at the control rate (50 Hz) on fresh
    samples. position: trunk in the world frame (z = height above the ground plane the anchor defines); yaw: the
    IMU's."""

    def __init__(self, anchors="alpha16", scene=SCENE, model=None):
        self.name = anchors
        self.corners = [np.asarray(c, float) for c in ANCHOR_SETS[anchors]]
        self.fk = LegFK(scene, model)
        self.reset()

    def reset(self):
        self.anchor_foot = LEFT
        self.anchor_local = np.zeros(3)
        self.anchor_xy = np.zeros(2)
        self.position = np.zeros(3)
        self.yaw = 0.0
        self.pending = None               # (foot, local point, world xy)
        self.pending_ticks = 0
        self.needs_init = True
        self.switches = 0
        self._shift = None                # set_pose() before the first update

    def update(self, joints, quat_wxyz=None, R=None):
        """joints: 14 measured servo angles in harness.JOINT_NAMES order; the trunk orientation as an IMU quaternion
        (w, x, y, z) or a 3x3 rotation R."""
        R = quat_to_mat(quat_wxyz) if R is None else np.asarray(R, float)
        feet = self.fk.feet(np.asarray(joints, float))
        if self.needs_init:
            self.anchor_xy = (R @ feet[self.anchor_foot][0])[:2].copy()   # trunk starts at (0, 0)
            self.needs_init = False
            if self._shift is not None:
                self.anchor_xy += self._shift
                self._shift = None
        self._reproject(R, feet)
        cand = self._lowest_corner(R, feet)
        if cand is None:
            self.pending, self.pending_ticks = None, 0
        else:
            if self.pending is not None and self.pending[0] == cand[0]:
                self.pending_ticks += 1
            else:
                self.pending, self.pending_ticks = cand, 1
            if self.pending_ticks >= SWITCH_CONFIRM_TICKS:
                # (as lib.rs: the claim that started the run is the one taken, with the X/Y it had then)
                foot, local, world_xy = self.pending
                self.pending = None
                self.anchor_foot, self.anchor_local, self.anchor_xy = foot, local, world_xy
                self._reproject(R, feet)
                self.pending_ticks = 0
                self.switches += 1
        self.yaw = yaw_of(R)
        return self.position

    def set_pose(self, xy, yaw=None):
        """Move the estimate to a known X/Y (a landmark fix): shifts the anchor, so tracking goes on from there.
        The yaw is the IMU's; pass the corrected heading in the next update's rotation."""
        d = np.asarray(xy, float) - self.position[:2]
        if self.needs_init:
            self._shift = d if self._shift is None else self._shift + d
        else:
            self.anchor_xy = self.anchor_xy + d
        self.position[:2] += d

    def _reproject(self, R, feet):
        pos, rot = feet[self.anchor_foot]
        contact = R @ (rot @ self.anchor_local + pos)
        self.position = np.array([self.anchor_xy[0] - contact[0], self.anchor_xy[1] - contact[1], -contact[2]])

    def _lowest_corner(self, R, feet):
        lowest, best = -SWITCH_MARGIN, None
        for foot, (pos, rot) in enumerate(feet):
            world = self.position + (self.corners[foot] @ rot.T + pos) @ R.T
            i = int(np.argmin(world[:, 2]))
            if world[i, 2] < lowest:
                lowest = world[i, 2]
                best = (foot, self.corners[foot][i].copy(), world[i, :2].copy())
        return best


class SimIMU:
    """A gyro + accelerometer attitude filter, as the robot's IMU fusion would run it (Mahony, 200 Hz): integrate the
    gyro quaternion-wise (strapdown) and pull the tilt towards the accelerometer's gravity (gain KP); the heading is
    the integrated gyro's (no magnetometer). Sensor model (assumed, BMI088-class after the start-up calibration):
    white noise 0.014 deg/s/sqrt(Hz), a residual bias U(+-0.05) deg/s per axis per body, accelerometer = MuJoCo's
    imu_accel (specific force: gravity plus the trunk's own accelerations) + N(0, 0.02 g).

    Why not soccer.py's heading (gyro . gravity integrated): that is the rate about the world vertical, which is the
    yaw rate only when level; with the gait's roll/pitch rocking the difference rectifies into a drift (measured
    here: ~+0.25 deg/s on a 0.5 m/s walk, 10 deg in 45 s, always the same sign). Integrating the full quaternion has
    no such term (0.000 deg after 45 s with a perfect gyro)."""

    KP = 0.5
    NOISE = math.radians(0.014) * math.sqrt(200.0)      # per-sample std at 200 Hz
    BIAS = math.radians(0.05)

    def __init__(self, sim, yaw0=0.0, seed=0, noise=True):
        self.sim, self.noise = sim, noise
        self.rng = np.random.default_rng(20_000 + seed)
        self.bias = self.rng.uniform(-self.BIAS, self.BIAS, 3) if noise else np.zeros(3)
        R0 = imu_rotation(sim.gravity(), yaw0)          # start: tilt from the accelerometer, heading given
        self.q = _mat_to_quat(R0)
        s = sim.m.sensor("imu_accel")
        self.acc_adr = slice(int(s.adr[0]), int(s.adr[0]) + 3)
        self.dt = float(sim.m.opt.timestep)

    def substep(self, sim=None):
        sim = sim or self.sim
        w = np.array(sim.d.sensordata[sim.gyro_adr], float)
        a = np.array(sim.d.sensordata[self.acc_adr], float)
        if self.noise:
            w = w + self.bias + self.rng.normal(0, self.NOISE, 3)
            a = a + self.rng.normal(0, 0.02 * 9.81, 3)
        n = np.linalg.norm(a)
        if n > 1e-6:
            R = quat_to_mat(self.q)
            up_est = R[2]                                 # world up in the trunk frame
            w = w + self.KP * np.cross(a / n, up_est)
        self.q = _quat_integrate(self.q, w, self.dt)

    @property
    def R(self):
        return quat_to_mat(self.q)

    @property
    def yaw(self):
        return yaw_of(self.R)

    def set_yaw(self, yaw):
        R = self.R
        self.q = _mat_to_quat(rot_z(yaw - yaw_of(R)) @ R)


def _quat_integrate(q, w, dt):
    th = float(np.linalg.norm(w)) * dt
    if th < 1e-12:
        return q
    ax = w / np.linalg.norm(w)
    dq = np.r_[math.cos(th / 2), math.sin(th / 2) * ax]
    w0, x0, y0, z0 = q
    w1, x1, y1, z1 = dq
    out = np.array([w0 * w1 - x0 * x1 - y0 * y1 - z0 * z1, w0 * x1 + x0 * w1 + y0 * z1 - z0 * y1,
                    w0 * y1 - x0 * z1 + y0 * w1 + z0 * x1, w0 * z1 + x0 * y1 - y0 * x1 + z0 * w1])
    return out / np.linalg.norm(out)


def _mat_to_quat(R):
    import mujoco
    q = np.zeros(4)
    mujoco.mju_mat2Quat(q, np.asarray(R, float).ravel())
    return q


class SimOdometry:
    """Odometry fed from a harness.MicroduckSim the way the robot would be: encoder angles (qpos + U(+-0.001) rad,
    Microduck's joint observation noise) and the IMU's orientation.
    heading='imu' (default): SimIMU's quaternion (gyro + accelerometer fusion, sensor noise and bias), used whole,
    as lib.rs uses the IMU quaternion. heading='gyro_up': soccer.Player's heading (gyro . gravity integrated at 200 Hz)
    with the tilt from gravity (+ U(+-0.01)). perfect=True: the true joint angles and trunk rotation (Pollen's
    --odom-compare setting). Call substep(sim) every physics step (rt.on_substep) and update() after every tick.
    pos0/yaw0: where the duck starts (field frame)."""

    def __init__(self, sim, pos0=(0.0, 0.0), yaw0=0.0, anchors="alpha16", noise=True, perfect=False, seed=0,
                 heading="imu"):
        self.sim, self.noise, self.perfect, self.heading = sim, noise, perfect, heading
        self.rng = np.random.default_rng(10_000 + seed)
        self.odo = Odometry(anchors, model=sim.m)
        self.imu = SimIMU(sim, yaw0, seed, noise) if heading == "imu" else None
        self.psi = float(yaw0)
        self.pos0 = np.asarray(pos0, float)
        self.dt = float(sim.m.opt.timestep)

    def substep(self, sim=None):
        sim = sim or self.sim
        if self.imu is not None:
            self.imu.substep(sim)
            return
        up = -sim.gravity()
        self.psi = (self.psi + float(sim.d.sensordata[sim.gyro_adr] @ up) * self.dt + math.pi) % (2 * math.pi) - math.pi

    def update(self):
        sim = self.sim
        if self.perfect:
            q = sim.d.qpos[sim.qadr].copy()
            R = sim.d.xmat[sim.trunk].reshape(3, 3).copy()
        else:
            q = sim.d.qpos[sim.qadr] + (self.rng.uniform(-0.001, 0.001, 14) if self.noise else 0.0)
            if self.imu is not None:
                R = self.imu.R
            else:
                g = sim.gravity() + (self.rng.uniform(-0.01, 0.01, 3) if self.noise else 0.0)
                R = imu_rotation(g, self.psi)
        if self.odo.needs_init:
            self.odo.set_pose(self.pos0)
        self.odo.update(q, R=R)
        return self.xy

    def set_pose(self, xy, yaw=None):
        """A landmark fix (e.g. soccer's goal sighting): position and, if given, heading."""
        if yaw is not None:
            self.psi = float(yaw)
            if self.imu is not None:
                self.imu.set_yaw(yaw)
        self.odo.set_pose(xy)

    @property
    def xy(self):
        return self.odo.position[:2].copy()

    @property
    def yaw(self):
        if self.perfect:
            return self.odo.yaw
        return self.imu.yaw if self.imu is not None else self.psi

    @property
    def z(self):
        return float(self.odo.position[2])
